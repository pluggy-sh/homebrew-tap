  on_macos do
    on_arm do
      url "https://github.com/pluggy-sh/pluggy/releases/download/v#{version}/pluggy-darwin-arm64"
      sha256 "18fff1b5885dac79fd2e74e5a500a0fa7c968ff3c97a7196ea6689af6d5df922"
